"""Write docs/STAGE_01_GREYBOX_REPORT.md from the spec, the metadata JSON and the validation JSON.

Plain Python (no Blender needed). Run after run_stage.sh:

    python3 blender/scripts/report_greybox.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPEC = json.loads((ROOT / "blender/scripts/specs/stg01_greybox.json").read_text())
EXP = ROOT / "blender/exports/STG01"
META = json.loads((EXP / f"{SPEC['blend_name']}_METADATA.json").read_text())
VAL = json.loads((EXP / "STG01_validation.json").read_text())
OBJ = {o["name"]: o for o in META["objects"]}


def f(v, n=2):
    return f"{v:.{n}f}".rstrip("0").rstrip(".") if isinstance(v, float) else str(v)


def row(name, label=None):
    o = OBJ[name]
    mn, mx, d = o["bounds_min_m"], o["bounds_max_m"], o["dimensions_m"]
    return (f"| {label or name} | `{name}` | {f(mn[0])} … {f(mx[0])} | {f(mn[1])} … {f(mx[1])} | {f(mn[2])} … {f(mx[2])} | "
            f"{f(d[0])} × {f(d[1])} × {f(d[2])} |")


def main() -> None:
    s = SPEC
    st = VAL["stats"]
    lines = [
        "# CN Trials · Stage 01 greybox report (Prompt 03)",
        "",
        f"Status: **blockout complete, awaiting approval**. Generated by `blender/scripts/report_greybox.py` from the "
        f"build spec (v{s['spec_version']}, hash `{VAL['spec_hash']}`), `{SPEC['blend_name']}_METADATA.json` and "
        f"`STG01_validation.json`. Do not edit by hand; re-run the scripts.",
        "",
        "## Build",
        "",
        "| Item | Value |",
        "|------|-------|",
        f"| Blender | {VAL['blender']} (official `bpy` 5.3.0 module, pinned in decision 002) |",
        "| Execution | Headless Blender Python in the Claude cloud session: `bash blender/scripts/run_stage.sh STG01` "
        "(build → export → validate → renders → browser check). The same scripts run inside desktop Blender with "
        "`blender --background --python <script> -- <args>` |",
        f"| Generator | `blender/scripts/{s['generator']}` (rebuilds the scene from the spec; safe to re-run) |",
        "| Source of truth | `docs/STAGE_01_DESIGN_SPEC.md` (approved, decision 017) and `docs/STAGE_01_SPEC.md` v0.2, "
        "encoded in `blender/scripts/specs/stg01_greybox.json` |",
        "| Units and axes | Metres; Blender Z up, X across (west −, east +), Y along the course (start line 0, finish 160). "
        "Game/glTF = (x, z, −y) |",
        "",
        "## Files",
        "",
        "| Output | Path |",
        "|--------|------|",
        f"| Scene | `blender/scenes/{s['blend_name']}.blend` |",
        f"| Generator script | `blender/scripts/{s['generator']}` |",
        f"| Runtime GLB (loaded by the live game) | `blender/exports/STG01/{s['blend_name']}.glb` |",
        f"| Metadata (every object: id, collection, role, location, rotation, dimensions) | `blender/exports/STG01/{s['blend_name']}_METADATA.json` |",
        "| Server collision and markers | `blender/exports/STG01/STG01_collision.json`, `STG01_markers.json` |",
        "| Validation report | `blender/exports/STG01/STG01_validation.json` (summarised below) |",
        "| Top-down render | `renders/STAGE_01_GREYBOX_TOP.png` |",
        "| Front perspective render | `renders/STAGE_01_GREYBOX_PERSPECTIVE.png` |",
        "| Third-person gameplay render | `renders/STAGE_01_GREYBOX_THIRD_PERSON.png` |",
        "| All camera previews | `blender/exports/STG01/previews/` |",
        "",
        "## Collections",
        "",
        "| Collection | Contents | In the game file |",
        "|------------|----------|------------------|",
        "| `00_REFERENCE` | 1.2 m scale figure, north arrow | No (review only) |",
        "| `01_ARCHITECTURE` | Ground, fences, finish gate, start barrier, Shepherd platform, spectator gantry, judges' booth, benches, service gates | Yes |",
        "| `02_GAMEPLAY_ZONES` | Start and finish bands, lane lines, gameplay markers; zone overlays and the 110° coverage wedge | Markings and markers yes; overlays and wedge no |",
        "| `03_ENVIRONMENT_BLOCKERS` | Outer barrier, playground relics, roadway, water tower, trees, silhouettes. **None inside the course**: Stage 01 has cover-free lanes (GDD §3) | Yes |",
        "| `04_WATCHER_PLACEHOLDER` | The Shepherd proxy (body, head, face, lantern, crook); facing arrow and 8 × 8 × 28 m envelope | Proxy yes; arrow and envelope no |",
        "| `05_LIGHTING_PLACEHOLDERS` | 10 floodlight towers with heads, signal lamps, 4 loudspeakers; 10 spot lights and moonlight | Meshes yes; lights no |",
        "| `06_COLLISION` | Simplified boxes: ground, 4 walls, finish and safe triggers, 3 camera-only fence boxes | No (server reads `STG01_collision.json`) |",
        "| `07_PLAYER_SPAWNS` | `GMK_SPAWN_01`–`30` markers plus capsule proxies at the 0.3 m player radius | Markers yes; capsules no |",
        "| `08_CAMERAS` | Top-down (orthographic), front perspective, third person, intro, spectator, finish, overview | No |",
        "",
        "## Dimensions and coordinates",
        "",
        "Blender coordinates in metres (bounds are world-space boxes).",
        "",
        "| Element | Object | X | Y | Z | Size (X × Y × Z) |",
        "|---------|--------|---|---|---|------------------|",
    ]
    for name, label in (
        ("ZONE_STG01_Start", "Start zone"), ("ZONE_STG01_Course", "Competition ground (course)"),
        ("ZONE_STG01_Finish", "Finish zone (qualify)"), ("ZONE_STG01_Safe", "Safe zone"),
        ("STG01_Ground_Yard", "Yard surface"), ("STG01_StartBand", "Start line band"), ("STG01_FinishBand", "Finish line band"),
        ("PRP_STG01_Fence_W", "Fence west"), ("PRP_STG01_Fence_E", "Fence east"), ("PRP_STG01_Fence_S", "Fence south (start wall)"),
        ("PRP_STG01_Fence_N", "Fence north (back wall)"), ("PRP_STG01_FinishGate_Beam", "Finish gate beam"),
        ("PRP_STG01_FinishGate_Post_W", "Finish gate post west"), ("PRP_STG01_StartBarrier_Arm", "Start barrier arm (raised)"),
        ("PRP_STG01_ShepherdPlatform", "Shepherd platform"), ("ENM_Shepherd_Placeholder_Body", "Shepherd body"),
        ("ENM_Shepherd_Placeholder_Head", "Shepherd head"), ("PRP_STG01_SpectatorGantry_Deck", "Spectator gantry deck"),
        ("PRP_STG01_SpectatorGantry_Roof", "Spectator gantry roof"), ("PRP_STG01_JudgesBooth_Cabin", "Judges' booth"),
        ("PRP_KIT_Bench_01", "Bench 1 (of 15, every 10 m)"), ("PRP_KIT_ServiceGate_01", "Service gate 1"),
        ("PRP_KIT_FloodlightTower_01", "Floodlight tower 1 (of 10)"), ("PRP_KIT_FloodlightTower_Head_01", "Floodlight head 1"),
        ("PRP_KIT_ConcreteBarrier_W", "Outer barrier west"), ("PRP_STG01_RocketFrame_A", "Rocket frame relic"),
        ("STG01_BG_Overpass_Deck", "Elevated roadway deck"), ("STG01_BG_WaterTower_Tank", "Water tower tank"),
        ("COL_STG01_Wall_S", "Collision: start wall"), ("COL_STG01_FinishTrigger", "Collision: finish trigger"),
        ("COL_STG01_SafeZone", "Collision: safe-zone trigger"),
    ):
        lines.append(row(name, label))
    towers = sorted((o for o in META["objects"] if o["name"].startswith("PRP_KIT_FloodlightTower_") and "Head" not in o["name"] and o["name"][-1].isdigit()),
                    key=lambda o: o["name"])
    lines += [
        "",
        "Floodlight towers (centre X, Y): " + ", ".join(f"({f(o['location_m'][0])}, {f(o['location_m'][1])})" for o in towers) + "; 22 m tall.",
        "",
        "### Spawns",
        "",
        f"30 markers, 10 per row, facing +Y. Lateral spacing {f(s['spawns']['spacing_x'])} m, rows at Y "
        + ", ".join(f(y) for y in s["spawns"]["row_y"]) + f". Capsule radius {f(s['capsule']['radius'])} m, height {f(s['capsule']['height'])} m. "
        f"Smallest gap between two capsules: **{f(st['min_spawn_gap_m'])} m** (no overlaps).",
        "",
        "| Spawn | X | Y | Spawn | X | Y | Spawn | X | Y |",
        "|-------|---|---|-------|---|---|-------|---|---|",
    ]
    sp = {o["name"]: o for o in META["objects"] if o["name"].startswith("GMK_SPAWN_") and o["type"] == "EMPTY"}
    for i in range(1, 11):
        cells = []
        for k in (i, i + 10, i + 20):
            o = sp[f"GMK_SPAWN_{k:02d}"]
            cells += [f"{k:02d}", f(o["location_m"][0]), f(o["location_m"][1])]
        lines.append("| " + " | ".join(cells) + " |")
    sh = s["shepherd"]
    lines += [
        "",
        "### The Shepherd (Watcher placeholder)",
        "",
        f"Platform centre ({f(sh['x'])}, {f(sh['y'])}), 12 × 12 m, top Z {f(sh['platform_height'])} m. Figure {f(sh['height'])} m "
        f"(top Z {f(sh['platform_height'] + sh['height'])} m, head centre Z {f(OBJ['ENM_Shepherd_Placeholder_Head']['location_m'][2])} m). "
        "Faces −Y toward the players. Coverage marker: 110° wedge (±55°) from the platform, reaching every corner of the yard. "
        "Detection itself is server-side and not line-of-sight (decision E9).",
        "",
        "### Cameras",
        "",
        "| Camera | Position | Looks at | Type |",
        "|--------|----------|----------|------|",
    ]
    for name, c in s["environment"]["cameras"].items():
        typ = "orthographic" if "ortho_scale" in c else "perspective"
        lines.append(f"| `{name}` | {tuple(c['pos'])} | {tuple(c['look'])} | {typ}{' (review render)' if c.get('review_name') else ''} |")
    lines += [
        "",
        "## Validation",
        "",
        f"Overall: **{VAL['result']}**, {len(VAL['errors'])} errors, {len(VAL['warnings'])} warnings. "
        f"{st['objects']} objects; {st['runtime_meshes']} runtime meshes; {st['runtime_triangles']:,} triangles (budget {st['triangle_budget']:,}).",
        "",
        "| # | Check | Result | Detail |",
        "|---|-------|--------|--------|",
    ]
    for key, c in sorted(VAL["checks"].items(), key=lambda kv: int(kv[0].split("_")[0])):
        lines.append(f"| {key.split('_')[0]} | {c['title']} | {c['result']} | {c['detail']} |")
    lines += [
        "",
        "Also checked by `run_stage.sh`: the Khronos glTF Validator (0 errors) and a headless Chromium load of the GLB with "
        "Three.js (markers and extras present, no collision, camera, light or review-only objects in the file).",
        "",
        "The checks were proven on a deliberately broken copy: an overlapping spawn, a floating box, a coplanar decal, a "
        "duplicate collider and a collider in the wrong collection were each reported.",
    ]
    if VAL["errors"]:
        lines += ["", "### Errors", ""] + [f"- {e}" for e in VAL["errors"]]
    lines += [
        "",
        "## Deviations and decisions for approval",
        "",
        "| # | Item | Status |",
        "|---|------|--------|",
        "| G1 | **Start barrier arm raised to 6 m** (approved spec: raised 2.8 m). At 2.8 m the arm ran across the third-person view at The Shepherd's feet; at 6 m it is overhead and above every sightline. Lowered position before GO stays 1.1 m | Needs approval |",
        "| G2 | **File names** follow this brief: `STAGE_01_GREYBOX.blend`, `generate_stage_01_greybox.py`, `STAGE_01_GREYBOX.glb` (were `STG01_RedLightGreenLight.*`, `build_stg01_greybox.py`). Exports stay in the established `blender/exports/STG01/` folder | Applied |",
        "| G3 | **Collections** follow this brief (`00_REFERENCE` … `08_CAMERAS`), replacing the pipeline's `STG01_ENV/PROPS/…`. New prefixes `ZONE_` (zone overlays) and `REF_` (reference aids); review-only objects carry `review_only` and never reach the game | Applied; `BLENDER_PIPELINE.md` updated |",
        "| G4 | **\"Environmental obstacles\"**: Stage 01 has none inside the course (cover-free lanes, GDD §3 and design spec §7). `03_ENVIRONMENT_BLOCKERS` holds only what closes the world outside the yard | Confirm |",
        "| G5 | The Prompt 03 process screenshot is a third-party portfolio image with a watermark; it was used as a style example only and is not committed | Applied |",
        "",
        "## Next",
        "",
        "Stopping here for approval. After approval: S1-4 (red/green rules on the server, The Shepherd's turn, "
        "spotted walk-off, results, row shuffle), then the art pass.",
        "",
    ]
    out = ROOT / "docs/STAGE_01_GREYBOX_REPORT.md"
    out.write_text("\n".join(lines))
    print("wrote", out.relative_to(ROOT))


if __name__ == "__main__":
    main()
